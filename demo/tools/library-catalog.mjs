#!/usr/bin/env node
// THE LIBRARY, WRITTEN DOWN FOR THE RULES (lib-1): the city's cast and home kit are browser modules (the kit reaches
// three.js), so the run's rules read them from a data file this tool writes: src/run/library-data.mjs. Run it again
// after a cast re-sync (tools/sync-cast.mjs, never from here); test/run-library.test.mjs checks the cast half of the
// file against the registry node can read, so a stale file fails the tests. The server must be running.
//
//   node demo/tools/library-catalog.mjs [--port 5470] [--check] [--fit] [--out <dir>]
//     --check  compare with the file on disk, write nothing
//     --fit    also measure which home pieces fit nowhere in the starter trailer: the run's own page (demo/?mode=run),
//              at the crib, every home piece the rules allow owned and in the tray, each taken out (set/arrange.js
//              takeOut: the kit's own check and the run's walks, every turn): no spot at any turn is NOFIT, "too big".
//              With --out, the measure as fit.json there.
import path from 'node:path';
import { writeFileSync, readFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { launch } from './chrome.mjs';
import { homeRuleOut } from '../../src/run/library.mjs';
import { RUN_CONFIG } from '../../src/run/config.mjs';
const THINGS = { a: { lavalamp: 1, fishtank: 1, beanbag: 1, boxfan: 1, floorsafe: 1 } };   // (stage/set/starter.js THINGS.a: it needs a browser to import)

const opt = (name, fallback) => { const at = process.argv.indexOf(name); return at === -1 ? fallback : process.argv[at + 1]; };
const port = opt('--port', 5470);
const out = opt('--out', null);
const FILE = path.join(path.dirname(fileURLToPath(import.meta.url)), '../../src/run/library-data.mjs');

async function inPage(url, run, size = [800, 600]) {
  const browser = await launch({ width: size[0], height: size[1] });
  try {
    const page = await browser.open(url);
    return await run(page);
  } finally {
    await browser.close();
  }
}

const data = await inPage(`http://127.0.0.1:${port}/demo/tools/item-tiles.html?quiet`, async page => {
  await page.waitFor('window.__tiles && window.__tiles.ready', 120000, 100);
  return page.evaluate('window.__tiles.T.libraryData(window.__tiles.K)', 120000);
});

// the fit: what the rules allow, owned and in the tray; each taken out
let nofit = (() => {
  try {
    return readFileSync(FILE, 'utf8').match(/export const NOFIT = \[([\s\S]*?)\];/)?.[1].trim().split('\n').filter(Boolean).map(l => JSON.parse(l.replace(/,\s*$/, ''))) ?? [];
  } catch {
    return [];
  }
})();
const rows = (list, f) => list.map(x => `  ${JSON.stringify(f(x))},`).join('\n');
const textOf = nofit => `// GENERATED by demo/tools/library-catalog.mjs from the city's cast (world/cast/fresh, less its kills and uniform
// pieces) and home kit (style/city/interiors/home). Do not edit by hand: run the tool again after a cast re-sync.
// WEAR: [cast slot, id, name, pool, tier]. HOME: [id, name, cat, place, [w, d] cells of 0.25 m (a wall piece: [wide, tall]),
// height m (a wall piece: how far it stands off the wall), game kind, rarity, mount m (a wall piece: its bottom edge)].
// OUT: pieces of the wearable slots the city never rolls, and why. NOFIT: home pieces with no spot at any turn in the
// starter trailer (--fit, measured on the run's own page), and why.
export const WEAR = [
${rows(data.wear, w => [w.slot, w.id, w.name, w.pool, w.tier])}
];
export const HOME = [
${rows(data.home, o => [o.id, o.name, o.cat, o.place, o.foot, o.h, o.kind, o.rarity, o.mount])}
];
export const OUT = [
${rows(data.out, o => [o.piece, o.why])}
];
export const NOFIT = [
${rows(nofit, x => x)}
];
`;
// (the measure asks the page for every piece the rules allow: the file is written first with nothing measured out)
if (process.argv.includes('--fit')) writeFileSync(FILE, textOf([]));
if (process.argv.includes('--fit')) {
  const KEY = 'pad:a1';
  const A = `window.__demo.stage.inside.place(${JSON.stringify(KEY)}).arrange`;
  // (the library's pieces, less those a named thing already is; and the named things with no spot of their own, by their key)
  const named = new Map(Object.entries(RUN_CONFIG.things).filter(([, t]) => t.piece?.startsWith('kit:')).map(([k, t]) => [t.piece, k]));
  const keys = [...data.home.filter(o => !homeRuleOut(o) && !named.has(`kit:${o.id}`)).map(o => `kit:${o.id}`),
    ...Object.keys(RUN_CONFIG.things).filter(k => RUN_CONFIG.things[k].kind === 'home' && !THINGS.a[k] && RUN_CONFIG.things[k].piece !== 'kit:door-locks')];
  const fit = await inPage(`http://127.0.0.1:${port}/demo/?mode=run&seed=3`, async page => {
    const ev = (js, ms = 120000) => page.evaluate(js, ms);
    await page.waitFor(`window.__demo?.hud?.phase === 'choose' && window.__demo.hud.state.place === 'crib' && window.__demo.stage.inside.up === ${JSON.stringify(KEY)}`, 240000, 200);
    await page.waitFor(`!!${A}`, 60000, 200);
    await ev(`${A}.ready()`);
    // (owned for the measure only, ten at a time: the page's run, never saved by this tool's throwaway browser profile)
    const rows = [];
    const base = await ev('JSON.stringify(window.__demo.hud.state)');
    for (let b = 0; b < keys.length; b += 10) {
      const batch = keys.slice(b, b + 10);
      await ev(`(async () => { const h = window.__demo.hud; const s = JSON.parse(${JSON.stringify(base)}); s.things = { ...s.things, ...Object.fromEntries(${JSON.stringify(batch)}.map(k => [k, true])) }; return await h.load(s); })()`);
      await page.waitFor(`${A}.tray().length >= ${batch.length}`, 120000, 250);
      await page.sleep(800);
      for (const k of batch) {
        const t0 = Date.now();
        const r = await ev(`(async () => { const a = ${A}; const r = a.takeOut(${JSON.stringify(`L:${k}`)}); const held = a.held; if (r.ok) await a.cancel(); return { ok: r.ok, why: r.why, spots: held?.spots ?? 0, rot: held?.rot ?? null }; })()`, 300000);
        rows.push({ key: k, ...r, ms: Date.now() - t0 });
        console.log(`${r.ok ? 'fits' : 'NO  '} ${k} ${r.ok ? `${r.spots} spots at ${r.rot}°` : r.why} (${Date.now() - t0} ms)`);
      }
    }
    // A PIECE FOR A TABLE TOP: the starter's few tops are taken (the lamp, the cactus) or small, so a table piece that
    // found none is tried again on a desk the player could own (the kit's 'desk', 1.5 × 0.75 m), put down first
    const surface = new Set(data.home.filter(o => o.place === 'surface').map(o => `kit:${o.id}`));
    const again = rows.filter(r => !r.ok && surface.has(r.key));
    for (let b = 0; b < again.length; b += 10) {
      const batch = again.slice(b, b + 10).map(r => r.key);
      await ev(`(async () => { const h = window.__demo.hud; const s = JSON.parse(${JSON.stringify(base)}); s.things = { ...s.things, 'kit:desk': true, ...Object.fromEntries(${JSON.stringify(batch)}.map(k => [k, true])) }; return await h.load(s); })()`);
      await page.waitFor(`${A}.tray().length >= ${batch.length}`, 120000, 250);
      await page.sleep(800);
      // (the desk put down once stays where it was put for the next ten)
      const desk = await ev(`(async () => { const a = ${A}; if (!a.tray().some(t => t.key === 'L:kit:desk')) return { ok: true }; const r = a.takeOut('L:kit:desk'); if (!r.ok) return r; return await a.drop(); })()`, 300000);
      if (!desk.ok) throw new Error(`the desk would not go down: ${desk.why}`);
      await page.sleep(800);
      for (const k of batch) {
        const r = await ev(`(async () => { const a = ${A}; const r = a.takeOut(${JSON.stringify(`L:${k}`)}); const held = a.held; if (r.ok) await a.cancel(); return { ok: r.ok, why: r.why, spots: held?.spots ?? 0, rot: held?.rot ?? null }; })()`, 300000);
        Object.assign(rows.find(q => q.key === k), r.ok ? { ok: true, why: null, spots: r.spots, rot: r.rot, on: 'a desk' } : { why2: r.why });
        console.log(`${r.ok ? 'fits on a desk' : 'NO, not on a desk either'} ${k} ${r.ok ? `${r.spots} spots` : r.why}`);
      }
    }
    return rows;
  }, [1600, 1000]);
  if (out) {
    mkdirSync(out, { recursive: true });
    writeFileSync(path.join(out, 'fit.json'), JSON.stringify(fit, null, 1));
  }
  const wallIds = new Set(data.home.filter(o => o.place === 'wall').map(o => o.id));
  nofit = fit.filter(r => !r.ok && r.key.startsWith('kit:')).map(r => [r.key.slice(4), wallIds.has(r.key.slice(4))
    ? `too big for the trailer: no stretch of its three walls takes it, at any height under its 2.45 m ceiling, clear of the door, the window and what stands against the wall (${r.why})`
    : `too big for the trailer: no spot at any turn in the starter trailer (${r.why})`]);
}

const text = textOf(nofit);
if (process.argv.includes('--check')) {
  const same = readFileSync(FILE, 'utf8') === text;
  console.log(same ? 'library-data.mjs is up to date' : 'library-data.mjs is STALE: run demo/tools/library-catalog.mjs');
  process.exit(same ? 0 : 1);
}
writeFileSync(FILE, text);
console.log(`wrote ${FILE}: ${data.wear.length} to wear, ${data.home.length} home pieces, ${data.out.length} left out, ${nofit.length} too big`);
process.exit(0);
